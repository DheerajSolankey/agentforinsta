/**
 * Generate tiny local fixtures for tests / smoke renders (FFmpeg lavfi — no external assets).
 * Outputs into fixtures/ (gitignored).
 */
import { execFileSync } from 'child_process';
import { mkdirSync, existsSync, writeFileSync } from 'fs';
import { join, dirname } from 'path';
import { fileURLToPath } from 'url';
import { detectFfmpeg } from '../server/config.js';

const ROOT = dirname(dirname(fileURLToPath(import.meta.url)));
const FIX = join(ROOT, 'fixtures');

function ffmpeg(args) {
  const bin = detectFfmpeg();
  execFileSync(bin, ['-y', ...args], { stdio: 'pipe', windowsHide: true });
}

export function ensureFixtures({ force = false } = {}) {
  mkdirSync(FIX, { recursive: true });
  const clip = join(FIX, 'clip-1080x1920.mp4');
  const audio = join(FIX, 'tone-2s.wav');
  const image = join(FIX, 'frame.png');

  if (force || !existsSync(clip)) {
    // 3s 1080x1920 30fps color bars + sine tone
    ffmpeg([
      '-f', 'lavfi', '-i', `testsrc2=size=1080x1920:rate=30:duration=3`,
      '-f', 'lavfi', '-i', 'sine=frequency=440:duration=3',
      '-c:v', 'libx264', '-pix_fmt', 'yuv420p', '-preset', 'ultrafast', '-crf', '28',
      '-c:a', 'aac', '-b:a', '96k', '-shortest', clip,
    ]);
  }
  if (force || !existsSync(audio)) {
    ffmpeg([
      '-f', 'lavfi', '-i', 'sine=frequency=220:duration=2',
      '-ac', '2', '-ar', '48000', '-c:a', 'pcm_s16le', audio,
    ]);
  }
  if (force || !existsSync(image)) {
    ffmpeg([
      '-f', 'lavfi', '-i', 'testsrc2=size=1080x1920:rate=1:duration=1',
      '-frames:v', '1', image,
    ]);
  }
  // stamp a note so people know these are synthetic
  writeFileSync(join(FIX, 'README.txt'),
    'Synthetic fixtures generated by scripts/make-fixtures.js — safe to delete.\n');
  return { clip, audio, image, dir: FIX };
}

if (import.meta.url === `file://${process.argv[1].replace(/\\/g, '/')}` ||
    process.argv[1]?.endsWith('make-fixtures.js')) {
  const f = ensureFixtures({ force: process.argv.includes('--force') });
  console.log('Fixtures ready:', f);
}
